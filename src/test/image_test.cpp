static Str fixture(char const *s, iz len)
{
    return {(u8 *)s, len};
}
#define FIX(a) fixture(a, countof(a)-1)

static Str pxhex(Arena *a, u8 *p, iz len)
{
    Buf b(a, len*2);
    for (iz i = 0; i < len; i++) {
        printhex(&b, p[i], 2);
    }
    return finish(&b);
}

static Str imgshow(Arena *a, Str data, i64 max = 1<<20)
{
    Image p = imgdecode(a, data, max);
    if (p.err.data) {
        return concat(a, "error: ", p.err);
    }
    Str px = pxhex(a, p.rgba, (iz)p.width*p.height*4);
    return concat(a, concat(a, istr(a, p.width), concat(a, "x", istr(a, p.height))),
                  concat(a, " ", px));
}

// The largest difference of a channel from want, w by h RGBA, or -1 if
// it fails or its size differs.
static i32 imgdiff(Arena scratch, Str data, u8 *want, i32 w, i32 h)
{
    Image p = imgdecode(&scratch, data, 1<<20);
    if (p.err.data || p.width!=w || p.height!=h) {
        return -1;
    }
    i32 most = 0;
    for (iz i = 0; i < (iz)w*h*4; i++) {
        i32 d = p.rgba[i] - want[i];
        d     = d<0 ? -d : d;
        most  = d>most ? d : most;
    }
    return most;
}

// The fixtures' pixels, as their comments give them
static u8 *fxpixels(Arena *a, i32 w, i32 h, b32 alpha)
{
    u8 *r = alloc<u8>(a, w*h*4);
    for (i32 y = 0; y < h; y++) {
        for (i32 x = 0; x < w; x++) {
            u8 *p = r + (y*w + x)*4;
            p[0] = (u8)(x*37 + y*11);
            p[1] = (u8)(y*53 + 7);
            p[2] = (u8)(x*y*19 + 100);
            p[3] = alpha ? (u8)(40*x + 30*y + 15) : 255;
        }
    }
    return r;
}

static u8 *fxsmooth(Arena *a, i32 w, i32 h)
{
    u8 *r = alloc<u8>(a, w*h*4);
    for (i32 y = 0; y < h; y++) {
        for (i32 x = 0; x < w; x++) {
            u8 *p = r + (y*w + x)*4;
            p[0] = (u8)(x*12 + 40);
            p[1] = (u8)(y*10 + 60);
            p[2] = (u8)((x + y)*5 + 90);
            p[3] = 255;
        }
    }
    return r;
}

// A PNG of the given header, with a little image data after it, its
// CRCs right, so that only its size is wrong.
static Str pngheader(Arena *a, u32 w, u32 h)
{
    u8 *p = alloc<u8>(a, 8 + 25 + 12+2 + 12);
    copybytes(p, (u8 *)"\x89PNG\r\n\x1a\n", 8);
    u8 *c = p + 8;
    zput32be(c, 13);
    copybytes(c+4, (u8 *)"IHDR", 4);
    zput32be(c+8,  w);
    zput32be(c+12, h);
    c[16] = 8;  // depth
    c[17] = 6;  // RGBA
    zput32be(c+21, zcrc32(0, c+4, 17));
    c += 25;
    zput32be(c, 2);
    copybytes(c+4, (u8 *)"IDAT", 4);
    c[8] = 0x78;
    c[9] = 0x01;
    zput32be(c+10, zcrc32(0, c+4, 6));
    c += 14;
    zput32be(c, 0);
    copybytes(c+4, (u8 *)"IEND", 4);
    zput32be(c+8, zcrc32(0, c+4, 4));
    return {p, 8 + 25 + 14 + 12};
}

// Every prefix of an image fails cleanly, leaving the arena as it was,
// or decodes to its whole size (a GIF whose first frame is complete),
// and the first half always fails.
static b32 cutanywhere(Arena *a, Str src)
{
    Image whole = imgdecode(a, src, 1<<20);
    b32   ok    = !whole.err.data;
    for (iz n = 0; ok && n < src.len; n++) {
        Arena s   = *a;
        u8   *cpy = allocbytes(&s, n);  // so that nothing reads past it
        copybytes(cpy, src.data, n);
        byte *beg = s.beg;
        Image p   = imgdecode(&s, {cpy, n}, 1<<20);
        if (p.err.data) {
            ok = !p.rgba && s.beg==beg;
        } else {
            ok = n>=src.len/2 && p.width==whole.width && p.height==whole.height;
        }
    }
    return ok;
}

// Each byte past the signature flipped in turn: never out of bounds,
// and how many fail.
static i32 corruptions(Arena *a, Str src)
{
    i32 fails = 0;
    for (iz i = 8; i < src.len; i++) {
        Arena s   = *a;
        u8   *cpy = allocbytes(&s, src.len);
        copybytes(cpy, src.data, src.len);
        cpy[i] ^= (u8)(1 + i%255);
        Image p = imgdecode(&s, {cpy, src.len}, 1<<20);
        fails += p.err.len > 0;
    }
    return fails;
}

