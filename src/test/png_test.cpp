static Str pngfix(char const *s, iz len)
{
    return {(u8 *)s, len};
}

static Str hexstr(Arena *a, u8 *p, iz len)
{
    Buf b(a, len*2);
    for (iz i = 0; i < len; i++) {
        printhex(&b, p[i], 2);
    }
    return finish(&b);
}

static Str pngshow(Arena *a, Str png, i64 max = 1<<20)
{
    Png p = pngdecode(a, png, max);
    if (p.err.data) {
        return concat(a, "error: ", p.err);
    }
    Str px = hexstr(a, p.rgba, (iz)p.width*p.height*4);
    return concat(a, concat(a, istr(a, p.width), concat(a, "x", istr(a, p.height))),
                  concat(a, " ", px));
}

// Pack codes for symbols as deflate does, under the code lengths given,
// to decode them back through a table.
static Str huffpack(Arena *a, u8 *lens, i32 n, i32 *syms, i32 nsyms)
{
    i32 count[16] = {};
    i32 next[16]  = {};
    for (i32 i = 0; i < n; i++) count[lens[i]]++;
    count[0] = 0;
    for (i32 len = 1, code = 0; len < 16; len++) {
        code = (code + count[len-1]) << 1;
        next[len] = code;
    }
    i32 codes[32] = {};
    for (i32 i = 0; i < n; i++) {
        codes[i] = lens[i] ? next[lens[i]]++ : 0;
    }
    u8  *out = alloc<u8>(a, nsyms*2 + 8);
    iz   bit = 0;
    for (i32 k = 0; k < nsyms; k++) {
        i32 s = syms[k];
        for (i32 b = lens[s]-1; b >= 0; b--, bit++) {
            out[bit>>3] = (u8)(out[bit>>3] | (codes[s]>>b & 1) << (bit&7));
        }
    }
    return {out, (bit+7)/8};
}

